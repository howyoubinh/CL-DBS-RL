"""
Consolidate every final number into one markdown file, each with its source file. Reads the
summary.json files written by the analysis scripts; re-run after any of them changes.

Output: $CLDBS_NUMBERS_PATH (default figures/revision/REVISION_NUMBERS.md).

  python scripts/write_rev_numbers.py
"""
import json
import os

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
NUMBERS_PATH = os.environ.get('CLDBS_NUMBERS_PATH', os.path.join(ROOT, 'figures', 'revision', 'REVISION_NUMBERS.md'))
J = lambda p: json.load(open(os.path.join(ROOT, p)))
L = []
P = L.append


def row(cells):
    P('| ' + ' | '.join(str(c) for c in cells) + ' |')


def hdr(cells):
    row(cells); row(['---'] * len(cells))


P('# Revision numbers (generated by scripts/write_rev_numbers.py)\n')
P('All cycling numbers: 5 x 60 s blocks (healthy first), 100 ms decisions, mean over patients; PD β reduction vs the '
  'unstimulated run of the same patient; charge as % of cDBS (130 Hz / 0.3 ms / 300 µA) over the whole run; '
  'PD/healthy charge ratio = median over patients of (mean charge rate in PD blocks / mean in healthy blocks).\n')

# ---- final cycling (10 patients)
cy = J('data/revision/final_cycling/summary.json')
P('## Final cycling, 10 patients (`data/revision/final_cycling/summary.json`)\n')
hdr(['condition', 'n', 'PD β', 'PD β red. %', 'healthy β', 'charge % cDBS', 'PD/healthy ratio (med)', 'healthy off %'])
order = ['RT4_p202', 'RT4_p101', 'RT4_p303', 'xn_s0.03_w500', 'xylosim_xn_s0.03_w500', 'xn_s0.03_w5000',
         'mlp_mean80_p101', 'mlp_mean80_p202', 'mlp_mean80_p303', 'mlp_mean16_p101', 'mlp_mean16_p202', 'mlp_mean16_p303',
         'gru_raw80_p101', 'gru_raw80_p202', 'gru_raw80_p303', 'lstm_raw80_p101', 'lstm_raw80_p202', 'lstm_raw80_p303',
         'published', 'published_ann', 'published_gru', 'constant_180_0.06_212', 'constant_180_0.06_250', 'cdbs',
         'dual_230_290', 'integral_290_0.5_130_0.06', 'oracle_180_0.06_250']
for k in order:
    if k in cy:
        v = cy[k]; row([k, v['n'], f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['h_beta']:.0f}", f"{v['charge_pct']:.1f}", f"{min(v['ratio_median'], 1e4):.0f}", f"{v['h_off']:.0f}"])
P('\nReplicates and ablation (`data/revision/eval_round4b/summary.json`, 10 patients):\n')
rb = J('data/revision/eval_round4b/summary.json')['controllers']
hdr(['teacher', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
for k in sorted(rb):
    if k.startswith('RT4'):
        v = rb[k]; row([k, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{v['ratio_median']:.0f}", f"{v['h_off']:.0f}"])

# ---- acute
ac = J('data/revision/final_acute/summary.json')
P('\n## Final acute, 40 s sustained PD, 10 patients (`data/revision/final_acute/summary.json`)\n')
hdr(['condition', 'β', 'reduction % (mean ± sd)', 'charge % cDBS'])
for k in order:
    if k in ac:
        v = ac[k]; row([k, f"{v['beta']:.0f}", f"{v['reduction']:.1f} ± {v['reduction_sd']:.1f}", f"{v['charge_pct']:.1f}"])

# ---- students
st = J('data/revision/eval_students_round4/summary.json')
P('\n## Distilled students, cycling on patients 42–1024 (`data/revision/eval_students_round4/summary.json`)\n')
hdr(['student', 'ρ', 'λ', 'held-out joint agreement', 'hidden rate (spk/neuron/step)', 'PD β', 'charge %', 'ratio (med)', 'healthy off %'])
for k, v in st.items():
    if v.get('rho') is not None and 'pd_beta' in v:
        row([k, v['rho'], v['lam'], f"{v['agree']:.2f}", f"{v['rate']:.3f}", f"{v['pd_beta']:.0f}", f"{v['charge_pct']:.1f}", f"{v['ratio_median']:.0f}", f"{v['h_off']:.0f}"])
P(f"\nTeacher hidden rate: {next(v['teacher_rate'] for v in st.values() if v.get('teacher_rate')):.2f} spikes/neuron/step.\n")
xs = J('data/revision/eval_xylosim_round4/summary.json')
P('\n## Students on bit-accurate XyloSim vs fp32, cycling on patients 42–1024 (`data/revision/eval_xylosim_round4/summary.json`)\n')
hdr(['run', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
for k, v in xs.items():
    row([k, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{v['ratio_median']:.0f}", f"{v['h_off']:.0f}"])
P('\nXylo checks (`models/revision/students_round4/xn_*/xylo_check.json`): fp32 vs XyloSim joint action agreement, Q correlation, output-neuron resets:\n')
hdr(['student', 'joint agreement', 'agreement where fp32 margin ≥ 0.15', 'min Q corr', 'max Vmem/threshold', 'resets'])
import glob
for p in sorted(glob.glob(os.path.join(ROOT, 'models/revision/students_round4/xn_*/xylo_check.json'))):
    v = json.load(open(p)); x = v['xylosim']
    row([os.path.basename(os.path.dirname(p)), f"{x['agree_joint']:.2f}", f"{x['agree_clear']:.2f}", f"{min(x['q_corr']):.3f}", f"{v.get('vmem_out_over_threshold_max', float('nan')):.2f}", v.get('output_resets', '')])

# ---- baselines incl. sweep
bl = J('data/revision/eval_baselines_round4/summary.json')
P('\n## Baselines incl. hyperparameter sweep, cycling on 10 patients (`data/revision/eval_baselines_round4/summary.json`)\n')
hdr(['run', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
for k, v in bl.items():
    if k.startswith(('mlp', 'gru', 'lstm')):
        row([k, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{v['ratio_median']:.0f}", f"{v['h_off']:.0f}"])

# ---- robustness, blocks
for name, path in (('Robustness', 'data/revision/final_robustness/summary.json'), ('Block lengths', 'data/revision/final_blocks/summary.json')):
    rb = J(path)
    P(f'\n## {name}, cycling on patients 42–1024 (`{path}`)\n')
    hdr(['perturbation', 'controller', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
    for pt in rb:
        for c, v in rb[pt].items():
            row([pt, c, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{min(v['ratio_median'], 1e4):.0f}", f"{v['h_off']:.0f}"])

# ---- simple sweep
sw = J('data/revision/simple_sweep/summary.json')
P('\n## Simple controllers, cycling on patients 42–1024 (`data/revision/simple_sweep/summary.json`; `_sm10` = 1 s smoothed β)\n')
hdr(['controller', 'n', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
for k, v in sorted(sw.items()):
    row([k, v['n'], f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{min(v['ratio_median'], 1e4):.0f}", f"{v['h_off']:.0f}"])

# ---- teacher selection, hardened teachers
sel = J('data/revision/select_round4/summary.json')
P(f"\n## Teacher selection on patients 2048–9999 (`data/revision/select_round4/summary.json`): selected {sel['selected']}\n")
hdr(['teacher', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
for k, v in sel['controllers'].items():
    if k.startswith('RT4'):
        row([k, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{v['ratio_median']:.0f}", f"{v['h_off']:.0f}"])
if os.path.exists(os.path.join(ROOT, 'data/revision/eval_round5/summary.json')):
    r5 = J('data/revision/eval_round5/summary.json')['controllers']
    P('\n## Round-5 hardened teachers, cycling on 10 patients (`data/revision/eval_round5/summary.json`)\n')
    hdr(['teacher', 'PD β', 'PD β red. %', 'charge %', 'ratio (med)', 'healthy off %'])
    for k, v in r5.items():
        if k.startswith('RT4'):
            row([k, f"{v['pd_beta']:.0f}", f"{v['pd_red']:.1f}", f"{v['charge_pct']:.1f}", f"{min(v['ratio_median'], 1e4):.0f}", f"{v['h_off']:.0f}"])

hw = os.path.join(ROOT, 'data/revision/mcu_results/table1_numbers.json')
if os.path.exists(hw):
    t = json.load(open(hw))
    P('\n## Hardware: energy per 100 ms decision window (`data/revision/mcu_results/table1_numbers.json`; sources `stm32f746_2026-10-22.md`, `xylo_hdk_2026-10-22.md`)\n')
    hdr(['item', 'µJ per window', 'basis'])
    for k, v in t['rows'].items():
        row([k, f"{v['E_window_J'] * 1e6:.1f}", v['source']])
    P(f"\nXylo latency fit: host overhead {t['xylo_latency_fit']['host_overhead_s'] * 1e3:.0f} ms + chip compute {t['xylo_latency_fit']['compute_s_times_MHz'] * 1e3:.0f} ms·MHz / f. Chip vs carried-state XyloSim decisions 92/100, Q corr ≥ 0.994, vs fp32 82/100 (12.5 MHz, 100 windows).\n")
out = NUMBERS_PATH
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote', out, len(L), 'lines')
